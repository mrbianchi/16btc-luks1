//! LUKS1 passphrase verifier for the Tails 0.20.1 persistence partition.
//!
//! Re-implements the cryptsetup LUKS1 key-slot unlocking algorithm so it can
//! run entirely in the browser via WebAssembly:
//!
//!   PBKDF2-HMAC-SHA1(passphrase, slot.salt, slot.iterations) -> derived key
//!   AES-256-CBC with ESSIV:sha256 (IV = AES-ECB(SHA256(key), LE64(sector)||0))
//!   anti-forensic merge (XOR + SHA1 diffusion)
//!   PBKDF2-HMAC-SHA1(master_key, mk_digest_salt, mk_digest_iter) == mk-digest
//!
//! The target header is embedded at compile time and pointed at
//! `01_CRACKING_TARGET/myluksdrive-luks-header`.

mod utils;

